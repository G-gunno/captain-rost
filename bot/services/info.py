def section_body(body):
    """Вернуть текст секции: строку или результат вызова функции."""
    return body() if callable(body) else body


def info_menu_text():
    return "📖 <b>Капитан Рост — справка</b>\nВыберите раздел:"


def info_menu_markup():
    rows = [
        [InlineKeyboardButton(f"{emoji} {title}", callback_data=f"info:{i}")]
        for i, (emoji, title, _b) in enumerate(INFO_SECTIONS)
    ]
    return InlineKeyboardMarkup(rows)
