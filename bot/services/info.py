def section_body(body):
    """Вернуть текст секции: строку или результат вызова функции."""
    return body() if callable(body) else body


def info_full_text():
    """Собрать весь паспорт одним текстовым сообщением (без кнопок)."""
    parts = []
    for emoji, title, body in INFO_SECTIONS:
        parts.append(f"{emoji} <b>{title}</b>\n{section_body(body)}")
    return "\n\n".join(parts)
