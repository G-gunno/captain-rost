def _current_params():
    from bot.strategy.learner import learner
    from bot.strategy.shadow import shadow
    wr, _n = learner.winrate()
    t = shadow.tuning
    nudge_r = t.get('nudge_rocket', 0)
    nudge_s = t.get('nudge_sniper', 0)
    nudge_rev = t.get('nudge_reversal', 0)
    return (
        f"Winrate {wr:.0%} · режим: <b>{learner.current_risk_mode}</b>.\n"
        f"⚙️ Тюнинг: 🚀{nudge_r:+.2f} 🏹{nudge_s:+.2f} 🧲{nudge_rev:+.2f} · SL ×{t.get('sl_mult', 1):.2f}"
    )

