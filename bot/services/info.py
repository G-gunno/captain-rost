def section_body(body):
    return body() if callable(body) else body


def info_full_text():
    parts = []
    for emoji, title, body in INFO_SECTIONS:
        parts.append(f"{emoji} <b>{title}</b>\n{section_body(body)}")
    parts.append("\n📄 <i>Подробная техническая документация прикреплена файлом ниже.</i>")
    return "\n\n".join(parts)


