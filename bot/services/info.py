def section_body(body):
    return body() if callable(body) else body

def info_full_text():
    parts = []
    for emoji, title, body in INFO_SECTIONS:
        parts.append(f"{emoji} <b>{title}</b>\n{section_body(body)}")
    parts.append("\n📄 <i>Подробная техническая документация прикреплена файлом ниже.</i>")
    return "\n\n".join(parts)


def generate_whitepaper() -> str:
    doc = """=========================================================
CAPTAIN ROST: TECHNICAL WHITEPAPER & MECHANICS
=========================================================
Этот документ содержит исчерпывающее описание архитектуры,
формул и логики торгового бота CaptainRost.

1. АРХИТЕКТУРА И ТОРГОВЫЙ ЦИКЛ
---------------------------------------------------------
Бот работает на Event-Driven Architecture (EDA) через неблокирующую шину EventBus.
Основные воркеры:
- MarketDataWorker: котировки Bybit REST (кэш 5 сек).
- ScannerWorker: параллельный сканер и фильтрация структуры.
- OrderManagerWorker: бюджетирование совокупного риска Portfolio VaR и выставление заявок.
- PositionManagerWorker: динамический трейлинг, лестничный Runner и охрана позиций.
- ExecutionRiskWorker: исполнение стопов ровно по цене и математический безубыток.

2. ОЦЕНКА МАКРО-РЕЖИМА (REGIME)
---------------------------------------------------------
Функция get_regime() определяет фон рынка (bull, neutral, bear) по трем слоям:
1. Базовый тренд (BTCUSDT): Last > EMA50 > EMA200 -> 'bull'. Last < EMA50 < EMA200 -> 'bear'. Иначе 'neutral'.
2. Альт-сезон (Market Breadth): при нейтральном BTC, если >= 45% ликвидных альтов растут > 3% -> 'bull'.
3. Ончейн Ликвидность (DefiLlama): динамика стейблкоинов за 7 дней (приток > +0.5% -> bull, отток < -0.5% -> bear).

3. ПРИОРИТЕТ СТРУКТУРЫ (LOCATION FIRST) И СКОРИНГ
---------------------------------------------------------
Входы совершаются строго от подтвержденных уровней поддержки/сопротивления (S/R >= 2 касаний).
- Защита от пост-пампа: если актив вырос >= 12% и слился >= 40%, покупки блокируются.
- Паттерны Price Action: VCP сжатие, Spring пин-бар, бычье поглощение, истинный пробой.
- Индикаторы выступают валидаторами качества (EMA, RSI без слепых зон, объемы, сентимент).

4. РИСК-МЕНЕДЖМЕНТ И ПОРТФЕЛЬ (PORTFOLIO VAR)
---------------------------------------------------------
Торговые политики (Trade Policy):
- STRICT: макс. открытый риск всех стопов <= 1.5% депо. Альтернативные тактики только Grade A+.
- CAUTIOUS: макс. открытый риск <= 2.0% депо.
- NORMAL: макс. открытый риск <= 3.0% депо.
- AGGRESSIVE: макс. открытый риск <= 5.0% депо.

Безубыток рассчитывается строго по формуле спотовой комиссии Bybit:
Price_BE = Avg * (1 + fee) / (1 - fee) = Avg * 1.002002.
=========================================================
"""
    return doc
